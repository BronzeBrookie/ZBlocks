-- ZBlock secure catalogue setup for Supabase.
-- Run this in Supabase Dashboard -> SQL Editor.
-- This creates a public read-only catalogue and restricts writes to explicitly approved owner user IDs.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  category text not null default 'OTHER',
  price integer not null check (price > 0),
  stock integer not null default 0 check (stock >= 0),
  emoji text not null default '🧱',
  color text not null default '#f3e3ac',
  image text not null default '',
  gallery jsonb not null default '[]'::jsonb,
  description text not null default '',
  variants jsonb not null default '[{"name":"Standard","stock":0}]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.admin_users enable row level security;

-- Clear these grants first so permissions are intentional and predictable.
revoke all on table public.products from anon, authenticated;
revoke all on table public.admin_users from anon, authenticated;

grant select on table public.products to anon, authenticated;
grant insert, update, delete on table public.products to authenticated;
grant select on table public.admin_users to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

-- Public visitors may read the catalogue.
drop policy if exists "Public can read products" on public.products;
create policy "Public can read products"
  on public.products for select
  to anon, authenticated
  using (true);

-- Only a user explicitly listed in admin_users may create, edit, or remove products.
drop policy if exists "Only ZBlock owners can insert products" on public.products;
create policy "Only ZBlock owners can insert products"
  on public.products for insert
  to authenticated
  with check (exists (
    select 1 from public.admin_users a where a.user_id = (select auth.uid())
  ));

drop policy if exists "Only ZBlock owners can update products" on public.products;
create policy "Only ZBlock owners can update products"
  on public.products for update
  to authenticated
  using (exists (
    select 1 from public.admin_users a where a.user_id = (select auth.uid())
  ))
  with check (exists (
    select 1 from public.admin_users a where a.user_id = (select auth.uid())
  ));

drop policy if exists "Only ZBlock owners can delete products" on public.products;
create policy "Only ZBlock owners can delete products"
  on public.products for delete
  to authenticated
  using (exists (
    select 1 from public.admin_users a where a.user_id = (select auth.uid())
  ));

-- A signed-in user may read only their own admin_users row.
drop policy if exists "Users can read their own owner grant" on public.admin_users;
create policy "Users can read their own owner grant"
  on public.admin_users for select
  to authenticated
  using (user_id = (select auth.uid()));

